def pdf(pages):
    writer = PdfWriter()
    for text in pages:
        page = writer.add_blank_page(width=600, height=800)
        font = DictionaryObject({NameObject('/Type'): NameObject('/Font'), NameObject('/Subtype'): NameObject('/Type1'),
            NameObject('/BaseFont'): NameObject('/Helvetica')})
        page[NameObject('/Resources')] = DictionaryObject({NameObject('/Font'): DictionaryObject({NameObject('/F1'): writer._add_object(font)})})
        stream = DecodedStreamObject()
        lines = []
        for sentence in re.split(r'(?<=[.]) ', text):
            for start in range(0, len(sentence), 85):
                # Do not split words; source sentences are short enough for this fixture font.
                lines.append(sentence[start:start+85])
        escaped = [line.replace('\\', '\\\\').replace('(', '\\(').replace(')', '\\)') for line in lines]
        stream.set_data(('BT /F1 8 Tf 12 TL 30 750 Td ' + ' T* '.join(f'({line}) Tj' for line in escaped) + ' ET').encode('ascii'))
        page[NameObject('/Contents')] = writer._add_object(stream)
    output = BytesIO()
    writer.write(output)
    return output.getvalue()


def docx():
    document = Document()
    document.core_properties.created = document.core_properties.modified = datetime(2026, 10, 8, tzinfo=timezone.utc)
    for heading, text in PROTOCOL:
        document.add_heading(heading, 1)
        document.add_paragraph(text)
    stream = BytesIO()
    document.save(stream)
    # Pin ZIP metadata as well as document metadata so rebuild hashes are stable.
    result = BytesIO()
    with ZipFile(stream) as source, ZipFile(result, 'w', compression=ZIP_DEFLATED) as target:
        for name in sorted(source.namelist()):
            info = ZipInfo(name, date_time=(2026, 10, 8, 0, 0, 0))
            info.compress_type = ZIP_DEFLATED
            target.writestr(info, source.read(name))
    return result.getvalue()


